#include <stdio.h>

//xor process func
void xor_process(unsigned char *data,size_t data_len,unsigned char key){
    for (size_t i = 0;i<data_len;i++){
        data[i] = data[i] ^ key;
    }
}

//layers dec func
void dec_data(unsigned char *data,size_t data_len,unsigned char *keys,int num_layers){
    for (int i = num_layers -1 ; i >= 0; i--){
        xor_process(data,data_len,keys[i]);
    }
}

